-- Esquema inicial para servicios ocasionales y recurrentes.
create extension if not exists pgcrypto;

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id uuid not null references public.clients(id) on delete restrict,
  invoice_number bigint generated by default as identity,
  invoice_date date not null default current_date,
  due_date date,
  description text not null,
  service_type text not null default 'ocasional' check (service_type in ('ocasional','recurrente')),
  recurrence text check (recurrence in ('semanal','mensual','trimestral','anual') or recurrence is null),
  total numeric(12,2) not null check (total > 0),
  status text not null default 'pendiente' check (status in ('pendiente','pagada','anulada')),
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  invoice_id uuid not null references public.invoices(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  method text not null default 'efectivo',
  payment_date date not null default current_date,
  reference text,
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists clients_user_id_idx on public.clients(user_id);
create index if not exists invoices_user_id_idx on public.invoices(user_id);
create index if not exists invoices_client_id_idx on public.invoices(client_id);
create index if not exists payments_user_id_idx on public.payments(user_id);
create index if not exists payments_invoice_id_idx on public.payments(invoice_id);

alter table public.clients enable row level security;
alter table public.invoices enable row level security;
alter table public.payments enable row level security;

drop policy if exists "Clients owned by authenticated user" on public.clients;
create policy "Clients owned by authenticated user"
on public.clients for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Invoices owned by authenticated user" on public.invoices;
create policy "Invoices owned by authenticated user"
on public.invoices for all to authenticated
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (select 1 from public.clients c where c.id = client_id and c.user_id = auth.uid())
);

drop policy if exists "Payments owned by authenticated user" on public.payments;
create policy "Payments owned by authenticated user"
on public.payments for all to authenticated
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (select 1 from public.invoices i where i.id = invoice_id and i.user_id = auth.uid())
);
